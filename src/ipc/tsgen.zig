test "generate writes one method per registration" {
    const methods = [_]service.Method{
        .{ .name = "Greeter.greet", .invoke = noop, .arity = 1, .docs = "Says hello." },
        .{ .name = "Greeter.reset", .invoke = noop, .arity = 0 },
        .{ .name = "Files.list", .invoke = noop, .arity = 0 },
    };
    const text = try generate(std.testing.allocator, .{ .methods = &methods });
    defer std.testing.allocator.free(text);

    try std.testing.expect(std.mem.indexOf(u8, text, "Greeter: {") != null);
    try std.testing.expect(std.mem.indexOf(u8, text, "Files: {") != null);
    try std.testing.expect(std.mem.indexOf(u8, text, "greet(arg0: unknown): Promise<unknown>;") != null);
    try std.testing.expect(std.mem.indexOf(u8, text, "reset(): Promise<unknown>;") != null);
    try std.testing.expect(std.mem.indexOf(u8, text, "* Says hello.") != null);
}

fn noop(ctx: ?*anyopaque, args: @import("decode.zig").Args) @import("protocol.zig").Result {
    _ = ctx;
    _ = args;
    return .{ .ok = .null };
}

test "generate is deterministic" {
    const methods = [_]service.Method{
        .{ .name = "A.b", .invoke = noop },
        .{ .name = "A.c", .invoke = noop },
    };
    const first = try generate(std.testing.allocator, .{ .methods = &methods });
    defer std.testing.allocator.free(first);
    const second = try generate(std.testing.allocator, .{ .methods = &methods });
    defer std.testing.allocator.free(second);
    try std.testing.expectEqualStrings(first, second);
}
