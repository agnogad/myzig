//! TypeScript client generation.
//!
//! A page calling `window.myzig.call("Greeter.greet", name)` has no idea what
//! `greet` returns. This module reads the registered methods and writes a
//! `.d.ts` file that declares each one, so the editor completes method names
//! and checks argument and result types.
//!
//! ## What is generated
//!
//! * A `MyZigApi` interface with one property per service, and one method per
//!   service method.
//! * A `MyZigClient` interface with `call`, `emit`, `on`, `off`, `windowId`,
//!   `version`, plus the built-in `clipboard`, `dialog`, `notify`,
//!   `openExternal` helpers and the `Window` namespace.
//!
//! ## Types
//!
//! The registry stores an arity, not full signatures, because Zig cannot
//! reflect a function's parameter types from a function pointer. The generated
//! types come from the *declarations* the application supplies alongside its
//! methods: a `Method` may carry a `docs` string, and the generator maps the
//! arity to positional parameters of type `unknown`, which the application can
//! narrow by adding a handwritten overlay. Being honest about `unknown` beats
//! generating `any` and pretending the types are checked.

const std = @import("std");
const service = @import("service.zig");

/// Everything the generator needs, taken from a registry.
pub const Api = struct {
    methods: []const service.Method,
};

/// Writes the declaration file. The output is deterministic: methods appear in
/// registration order, so regenerating an unchanged app produces a byte-for-byte
/// identical file and cannot cause spurious diffs.
pub const Error = error{ OutOfMemory, LineTooLong };

pub fn generate(allocator: std.mem.Allocator, api: Api) Error![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(allocator);
    const w = Writer{ .list = &out, .allocator = allocator };

    try w.writeAll(header);

    // Group by namespace so the output reads like the service layout.
    // Namespaces are discovered in first-seen order to keep the file stable.
    var namespaces: std.ArrayList([]const u8) = .empty;
    defer namespaces.deinit(allocator);
    var seen: std.StringHashMapUnmanaged(void) = .empty;
    defer seen.deinit(allocator);

    for (api.methods) |m| {
        const dot = std.mem.indexOfScalar(u8, m.name, '.') orelse continue;
        const ns = m.name[0..dot];
        const gop = try seen.getOrPut(allocator, ns);
        if (!gop.found_existing) try namespaces.append(allocator, ns);
    }

    try w.writeAll("export interface MyZigApi {\n");
    for (namespaces.items) |ns| {
        try w.print("  {s}: {{\n", .{ns});
        for (api.methods) |m| {
            const dot = std.mem.indexOfScalar(u8, m.name, '.') orelse continue;
            if (!std.mem.eql(u8, m.name[0..dot], ns)) continue;
            try writeMethod(w, m);
        }
        try w.writeAll("  };\n");
    }
    try w.writeAll("}\n\n");

    try w.writeAll(footer);
    return out.toOwnedSlice(allocator);
}

/// A tiny writer over the list, because Zig 0.17 removed
/// `ArrayList.writer`. Keeping it here means the generator has one place to
/// express "append text" and no dependency on the std writer API.
const Writer = struct {
    list: *std.ArrayList(u8),
    allocator: std.mem.Allocator,

    fn writeAll(self: Writer, text: []const u8) Error!void {
        try self.list.appendSlice(self.allocator, text);
    }

    /// Formats into a stack buffer, which is enough for every line this
    /// generator writes: they are built from short names, never from content.
    fn print(self: Writer, comptime fmt: []const u8, args: anytype) Error!void {
        var buf: [1024]u8 = undefined;
        const text = std.fmt.bufPrint(&buf, fmt, args) catch return error.LineTooLong;
        try self.writeAll(text);
    }
};

fn writeMethod(w: Writer, m: service.Method) Error!void {
    const dot = std.mem.indexOfScalar(u8, m.name, '.') orelse return;
    const bare = m.name[dot + 1 ..];

    const docs = m.docs;
    if (docs.len > 0) {
        try w.writeAll("    /**\n");
        // One ` * ` prefix per line, wrapped as the author wrote it.
        var lines = std.mem.splitScalar(u8, docs, '\n');
        while (lines.next()) |line| {
            if (line.len == 0) {
                try w.writeAll("     *\n");
            } else {
                try w.print("     * {s}\n", .{line});
            }
        }
        try w.writeAll("     */\n");
    }

    try w.print("    {s}(", .{bare});
    var i: usize = 0;
    while (i < m.arity) : (i += 1) {
        if (i != 0) try w.writeAll(", ");
        try w.print("arg{d}: unknown", .{i});
    }
    try w.writeAll("): Promise<unknown>;\n");
}

