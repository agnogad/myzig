//! The platform backend contract.
//!
//! MyZig's core owns all behaviour that is not platform specific: option
//! defaults, the window registry, event listeners, the quit sequence, IPC
//! routing, menu models. A backend only translates this contract into native
//! calls and reports native events back.
//!
//! Rules for backends:
//!
//! * Every method runs on the **main thread**, the one that called `App.run`.
//!   No backend needs locks for its own state.
//! * Options arrive fully defaulted: backends never invent policy.
//! * A backend reports failures with the error sets declared in
//!   `errors.zig`, never by silently ignoring a call.
//! * A backend allocates only from the allocator passed to `init`, and frees
//!   everything in `deinit`.
//!
//! Three backends exist: `linux` (GTK 3 + WebKitGTK + X11/Wayland), `windows`
//! (Win32 + WebView2) and `macos` (AppKit + WKWebView). `testing` is an
//! in-memory backend that lets the whole framework, IPC included, run in a
//! unit test with no display.

const std = @import("std");
const errors = @import("../errors.zig");
const events = @import("../events.zig");

pub const Allocator = std.mem.Allocator;

pub const Backend = enum {
    linux,
    windows,
    macos,
    testing,

    pub fn name(self: Backend) []const u8 {
        return @tagName(self);
    }
};

/// The backend compiled for the current target. There is no fallback: a build
/// for an unsupported OS fails to compile, which is honest, rather than
/// succeeding and failing at run time.
///
/// A test build can select `testing` through the `myzig_backend` build option,
/// which is how the framework's own tests run with no display attached.
pub const current: Backend = blk: {
    if (@hasDecl(@import("myzig_options"), "backend")) {
        const name = @import("myzig_options").backend;
        break :blk std.meta.stringToEnum(Backend, name) orelse @compileError(
            "unknown myzig_backend: " ++ name,
        );
    }
    const builtin = @import("builtin");
    break :blk switch (builtin.os.tag) {
        .linux => .linux,
        .windows => .windows,
        .macos => .macos,
        else => @compileError(
            "MyZig supports Linux, Windows and macOS. " ++
                "For unit tests on other hosts, pass -Dmyzig_backend=testing.",
        ),
    };
};

/// Options the app hands to `Backend.init`. Fully defaulted.
pub const InitOptions = struct {
    /// Human readable application name, used for window titles, the WM class
    /// and the storage directories.
    name: []const u8 = "MyZig App",
    /// Reverse-DNS application id, e.g. `dev.example.notes`. Used on Wayland
    /// (app id), Windows (AppUserModelID) and macOS (bundle id).
    app_id: []const u8 = "dev.myzig.app",
    /// Version string shown in about panels and update checks.
    version: []const u8 = "0.0.0",
    /// Whether the backend should attach developer tools (web inspector,
    /// verbose logging).
    dev: bool = false,
    /// Disable the D-Bus/portal single-instance handover.
    single_instance: bool = false,
    /// A per-run random secret used to recognise trusted page messages.
    /// Generated by the core; the backend must pass it to webviews unchanged.
    secret: u64 = 0,
};

/// What a native window shows.
pub const ContentKind = enum {
    /// A web page in the system webview.
    web,
    /// Native UI drawn by MyZig into a GPU surface.
    native,
    /// A native surface and a web view composited together (hybrid).
    hybrid,
};

/// Defaulted window creation options. The core computes every default; a
/// backend uses these values directly.
pub const WindowOptions = struct {
    title: []const u8 = "",
    url: []const u8 = "",
    content: ContentKind = .web,

    /// Size in device independent pixels (DIPs).
    width: i32 = 800,
    height: i32 = 600,
    /// Position in DIPs; the window is centered when both are `null`.
    x: ?i32 = null,
    y: ?i32 = null,

    min_width: i32 = 0,
    min_height: i32 = 0,
    max_width: i32 = 0,
    max_height: i32 = 0,

    hidden: bool = false,
    frameless: bool = false,
    resizable: bool = true,
    movable: bool = true,
    minimizable: bool = true,
    maximizable: bool = true,
    closable: bool = true,
    fullscreenable: bool = true,
    always_on_top: bool = false,
    skip_taskbar: bool = false,
    transparent: bool = false,
    maximized: bool = false,
    fullscreen: bool = false,
    /// Backdrop colour while a page loads, as 0xRRGGBBAA.
    background: u32 = 0xffffffff,
    /// Parent window id for a modal or child window.
    parent: ?u32 = null,
    modal: bool = false,
    /// Per-window random token; the webview bridge uses it to authenticate
    /// page -> Zig messages.
    secret: u64 = 0,
};

/// A rectangle in screen coordinates, origin at the top-left of the primary
/// display, in DIPs.
pub const Rect = struct {
    x: i32,
    y: i32,
    width: i32,
    height: i32,

    pub fn contains(self: Rect, px: i32, py: i32) bool {
        return px >= self.x and py >= self.y and px < self.x + self.width and py < self.y + self.height;
    }
};

pub const MonitorInfo = struct {
    /// Bounds of the display in DIPs.
    bounds: Rect,
    /// Work area (bounds minus taskbar/menu bar).
    work_area: Rect,
    /// Scale factor, e.g. 1.0 or 2.0.
    scale: f32 = 1.0,
    /// Refresh rate in Hz, 0 when unknown.
    refresh_hz: f32 = 0,
    /// Whether this is the primary display.
    primary: bool = false,
    /// Human readable name, may be empty.
    name: []const u8 = "",
};

/// Events a backend delivers to the core. The core implements this interface.
pub const EventSink = struct {
    ctx: *anyopaque,
    vtable: *const VTable,

    pub const VTable = struct {
        // ------------------------------------------------ application level
        ready: *const fn (ctx: *anyopaque) void,
        all_windows_closed: *const fn (ctx: *anyopaque) void,
        quitting: *const fn (ctx: *anyopaque) void,
        activate: *const fn (ctx: *anyopaque) void,
        deactivate: *const fn (ctx: *anyopaque) void,
        open_url: *const fn (ctx: *anyopaque, url: []const u8) void,
        open_file: *const fn (ctx: *anyopaque, path: []const u8) void,

        // ------------------------------------------------- window lifecycle
        window_created: *const fn (ctx: *anyopaque, id: u32) void,
        window_closed: *const fn (ctx: *anyopaque, id: u32) void,
        window_close_requested: *const fn (ctx: *anyopaque, id: u32) void,
        window_focus: *const fn (ctx: *anyopaque, id: u32, focused: bool) void,
        window_resized: *const fn (ctx: *anyopaque, id: u32, width: i32, height: i32) void,
        window_moved: *const fn (ctx: *anyopaque, id: u32, x: i32, y: i32) void,
        window_state_changed: *const fn (ctx: *anyopaque, id: u32, state: events.WindowState) void,
        window_scale_changed: *const fn (ctx: *anyopaque, id: u32, scale: f32) void,
        window_theme_changed: *const fn (ctx: *anyopaque, id: u32, theme: events.Theme) void,

        // ------------------------------------------------------------ webview
        web_title_changed: *const fn (ctx: *anyopaque, id: u32, title: []const u8) void,
        web_url_changed: *const fn (ctx: *anyopaque, id: u32, url: []const u8) void,
        web_load_started: *const fn (ctx: *anyopaque, id: u32) void,
        web_load_finished: *const fn (ctx: *anyopaque, id: u32) void,
        web_load_failed: *const fn (ctx: *anyopaque, id: u32, reason: []const u8) void,
        web_dom_ready: *const fn (ctx: *anyopaque, id: u32) void,
        /// A message posted by the page's IPC bridge.
        web_message: *const fn (ctx: *anyopaque, id: u32, json: []const u8) void,
        web_console: *const fn (ctx: *anyopaque, id: u32, level: events.ConsoleLevel, text: []const u8) void,
        /// The page asks to navigate; returning false cancels it.
        web_navigation_requested: *const fn (ctx: *anyopaque, id: u32, url: []const u8) bool,

        // ----------------------------------------------------- native surface
        surface_resized: *const fn (ctx: *anyopaque, id: u32, width: i32, height: i32, scale: f32) void,
        surface_input: *const fn (ctx: *anyopaque, id: u32, input: events.Input) void,
        surface_frame_requested: *const fn (ctx: *anyopaque, id: u32) void,

        // ------------------------------------------------------------- desktop
        /// A menu entry the user clicked. `id` is the application's command id.
        menu_command: *const fn (ctx: *anyopaque, id: []const u8) void,
        notification_clicked: *const fn (ctx: *anyopaque, tag: []const u8) void,
        tray_clicked: *const fn (ctx: *anyopaque, item: u32) void,
        shortcut_pressed: *const fn (ctx: *anyopaque, accelerator: []const u8) void,
        theme_changed: *const fn (ctx: *anyopaque, theme: events.Theme) void,
        /// The main-thread queue has work; drain it.
        dispatch: *const fn (ctx: *anyopaque) void,
    };

    pub fn ready(self: EventSink) void {
        self.vtable.ready(self.ctx);
    }
    pub fn allWindowsClosed(self: EventSink) void {
        self.vtable.all_windows_closed(self.ctx);
    }
    pub fn quitting(self: EventSink) void {
        self.vtable.quitting(self.ctx);
    }
    pub fn activate(self: EventSink) void {
        self.vtable.activate(self.ctx);
    }
    pub fn deactivate(self: EventSink) void {
        self.vtable.deactivate(self.ctx);
    }
    pub fn openUrl(self: EventSink, url: []const u8) void {
        self.vtable.open_url(self.ctx, url);
    }
    pub fn openFile(self: EventSink, path: []const u8) void {
        self.vtable.open_file(self.ctx, path);
    }
    pub fn windowCreated(self: EventSink, id: u32) void {
        self.vtable.window_created(self.ctx, id);
    }
    pub fn windowClosed(self: EventSink, id: u32) void {
        self.vtable.window_closed(self.ctx, id);
    }
    pub fn windowCloseRequested(self: EventSink, id: u32) void {
        self.vtable.window_close_requested(self.ctx, id);
    }
    pub fn windowFocus(self: EventSink, id: u32, focused: bool) void {
        self.vtable.window_focus(self.ctx, id, focused);
    }
    pub fn windowResized(self: EventSink, id: u32, w: i32, h: i32) void {
        self.vtable.window_resized(self.ctx, id, w, h);
    }
    pub fn windowMoved(self: EventSink, id: u32, x: i32, y: i32) void {
        self.vtable.window_moved(self.ctx, id, x, y);
    }
    pub fn windowStateChanged(self: EventSink, id: u32, state: events.WindowState) void {
        self.vtable.window_state_changed(self.ctx, id, state);
    }
    pub fn windowScaleChanged(self: EventSink, id: u32, scale: f32) void {
        self.vtable.window_scale_changed(self.ctx, id, scale);
    }
    pub fn windowThemeChanged(self: EventSink, id: u32, theme: events.Theme) void {
        self.vtable.window_theme_changed(self.ctx, id, theme);
    }
    pub fn webTitleChanged(self: EventSink, id: u32, title: []const u8) void {
        self.vtable.web_title_changed(self.ctx, id, title);
    }
    pub fn webUrlChanged(self: EventSink, id: u32, url: []const u8) void {
        self.vtable.web_url_changed(self.ctx, id, url);
    }
    pub fn webLoadStarted(self: EventSink, id: u32) void {
        self.vtable.web_load_started(self.ctx, id);
    }
    pub fn webLoadFinished(self: EventSink, id: u32) void {
        self.vtable.web_load_finished(self.ctx, id);
    }
    pub fn webLoadFailed(self: EventSink, id: u32, reason: []const u8) void {
        self.vtable.web_load_failed(self.ctx, id, reason);
    }
    pub fn webDomReady(self: EventSink, id: u32) void {
        self.vtable.web_dom_ready(self.ctx, id);
    }
    pub fn webMessage(self: EventSink, id: u32, json: []const u8) void {
        self.vtable.web_message(self.ctx, id, json);
    }
    pub fn webConsole(self: EventSink, id: u32, level: events.ConsoleLevel, text: []const u8) void {
        self.vtable.web_console(self.ctx, id, level, text);
    }
    pub fn webNavigationRequested(self: EventSink, id: u32, url: []const u8) bool {
        return self.vtable.web_navigation_requested(self.ctx, id, url);
    }
    pub fn surfaceResized(self: EventSink, id: u32, w: i32, h: i32, scale: f32) void {
        self.vtable.surface_resized(self.ctx, id, w, h, scale);
    }
    pub fn surfaceInput(self: EventSink, id: u32, input: events.Input) void {
        self.vtable.surface_input(self.ctx, id, input);
    }
    pub fn surfaceFrameRequested(self: EventSink, id: u32) void {
        self.vtable.surface_frame_requested(self.ctx, id);
    }
    pub fn menuCommand(self: EventSink, id: []const u8) void {
        self.vtable.menu_command(self.ctx, id);
    }
    pub fn notificationClicked(self: EventSink, tag: []const u8) void {
        self.vtable.notification_clicked(self.ctx, tag);
    }
    pub fn trayClicked(self: EventSink, item: u32) void {
        self.vtable.tray_clicked(self.ctx, item);
    }
    pub fn shortcutPressed(self: EventSink, accel: []const u8) void {
        self.vtable.shortcut_pressed(self.ctx, accel);
    }
    pub fn themeChanged(self: EventSink, theme: events.Theme) void {
        self.vtable.theme_changed(self.ctx, theme);
    }
    pub fn dispatch(self: EventSink) void {
        self.vtable.dispatch(self.ctx);
    }
};

test "Rect contains" {
    const r = Rect{ .x = 10, .y = 10, .width = 100, .height = 50 };
    try std.testing.expect(r.contains(10, 10));
    try std.testing.expect(r.contains(109, 59));
    try std.testing.expect(!r.contains(110, 59));
    try std.testing.expect(!r.contains(9, 10));
}

test "current backend is known on supported hosts" {
    const name = current.name();
    try std.testing.expect(name.len > 0);
}
